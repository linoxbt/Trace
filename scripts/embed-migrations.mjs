// Writes the migration files into a module the scheduled function bundles
// (apps/web/netlify/migrations.gen.ts), so it can apply them at run time:
// Netlify's build can't reach the database, but the function can.
import { readdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const dir = join(root, "packages/db/migrations");
const list = readdirSync(dir)
  .filter((f) => /^\d+_.*\.sql$/.test(f))
  .sort()
  .map((name) => ({ name, sql: readFileSync(join(dir, name), "utf8") }));
const out = join(root, "apps/web/netlify/migrations.gen.ts");
writeFileSync(out, `// Generated by scripts/embed-migrations.mjs. Do not edit.\nexport const MIGRATIONS = ${JSON.stringify(list, null, 1)};\n`);
console.log(`embedded ${list.length} migrations`);
